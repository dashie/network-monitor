//! Create a minimal, runnable setup in a new folder.
//!
//! The folder is the unit of deployment: the configuration, the database directory, and the
//! event-log directory live together, and the printed commands are run from that folder. The
//! template is a constant, so it is validated at startup and the tests can parse it back.

use std::fs::{self, OpenOptions};
use std::io::Write;
use std::path::{Path, PathBuf};

use thiserror::Error;

use crate::config::{self, Config, Overrides};

/// The directory the monitor writes the database into, beside the configuration.
pub const DATA_DIR: &str = "data";
/// The directory the event log is written into, beside the configuration.
pub const LOG_DIR: &str = "logs";
/// The database path the generated configuration uses, relative to the folder.
pub const DATABASE: &str = "data/events.db";
/// The event-log path the generated configuration uses, relative to the folder.
pub const EVENT_LOG: &str = "logs/events.log";

/// The fixed configuration generated by `init`.
pub const TEMPLATE: &str = r#"# uptime-monitor.toml — generated by `uptime-monitor init`.
# Edit this file; `init` never overwrites it.
# Paths below are relative to this file, not to the working directory.
#   uptime-monitor check --config uptime-monitor.toml
#   uptime-monitor monitor --config uptime-monitor.toml
#
# The diagnostic log is written to stderr. The event log is `logs/events.log`,
# enabled as a `logfile` channel below and rotated by size.

interval_ms = 5000
timeout_ms = 2000
database = "data/events.db"
retention_days = 0

notify = ["events"]

[[notification]]
name = "events"
type = "logfile"
filename = "logs/events.log"
stabilize_seconds = 0
max_bytes = 10485760
max_files = 5

# A TCP target needs no privilege, so the setup runs as your user.
[[targets]]
method = "tcp"
host = "1.1.1.1"
port = 443
label = "cloudflare-https"

# ICMP needs root or CAP_NET_RAW. Uncomment and run the monitor with sudo:
# [[targets]]
# method = "icmp"
# ip = "1.1.1.1"
# label = "cloudflare-dns"
"#;

/// What `init` created, and where.
#[derive(Debug, Clone, PartialEq, Eq)]
pub struct Report {
    pub folder: PathBuf,
    pub config: PathBuf,
    pub data: PathBuf,
    pub logs: PathBuf,
}

impl Report {
    /// The paths that were created and the commands that use them.
    pub fn render(&self) -> String {
        format!(
            "created {}\ncreated {}/\ncreated {}/\n\nnext:\n  cd {}\n  uptime-monitor check --config {}\n  uptime-monitor monitor --config {}\n",
            self.config.display(),
            self.data.display(),
            self.logs.display(),
            self.folder.display(),
            config::DEFAULT_CONFIG_FILE,
            config::DEFAULT_CONFIG_FILE,
        )
    }
}

/// Why `init` refused to create a folder.
#[derive(Debug, Error)]
pub enum InitError {
    #[error("{path} is not a directory")]
    NotADirectory { path: PathBuf },
    #[error("{path} is not empty; choose a new or empty folder")]
    NotEmpty { path: PathBuf },
    #[error("cannot read {path}: {source}")]
    Read {
        path: PathBuf,
        source: std::io::Error,
    },
    #[error("cannot create {path}: {source}")]
    Create {
        path: PathBuf,
        source: std::io::Error,
    },
    #[error("cannot write {path}: {source}")]
    Write {
        path: PathBuf,
        source: std::io::Error,
    },
    #[error("the generated configuration is invalid: {reason}")]
    Template { reason: String },
}

/// Create the minimal setup in `folder`.
///
/// The folder must not exist or must be empty. The template is validated before the folder is
/// touched, and the configuration is the last file written, so a failure never leaves a file
/// that looks initialized.
pub fn run(folder: &Path) -> Result<Report, InitError> {
    validate_template()?;

    if folder.exists() {
        if !folder.is_dir() {
            return Err(InitError::NotADirectory {
                path: folder.to_path_buf(),
            });
        }
        let mut entries = fs::read_dir(folder).map_err(|source| InitError::Read {
            path: folder.to_path_buf(),
            source,
        })?;
        match entries.next() {
            Some(Ok(_)) => {
                return Err(InitError::NotEmpty {
                    path: folder.to_path_buf(),
                })
            }
            Some(Err(source)) => {
                return Err(InitError::Read {
                    path: folder.to_path_buf(),
                    source,
                })
            }
            None => {}
        }
    } else {
        fs::create_dir_all(folder).map_err(|source| InitError::Create {
            path: folder.to_path_buf(),
            source,
        })?;
    }

    let data = folder.join(DATA_DIR);
    let logs = folder.join(LOG_DIR);
    for directory in [&data, &logs] {
        fs::create_dir(directory).map_err(|source| InitError::Create {
            path: directory.clone(),
            source,
        })?;
    }

    let config = folder.join(config::DEFAULT_CONFIG_FILE);
    let mut file = OpenOptions::new()
        .write(true)
        .create_new(true)
        .open(&config)
        .map_err(|source| InitError::Write {
            path: config.clone(),
            source,
        })?;
    file.write_all(TEMPLATE.as_bytes())
        .and_then(|()| file.flush())
        .map_err(|source| InitError::Write {
            path: config.clone(),
            source,
        })?;

    Ok(Report {
        folder: folder.to_path_buf(),
        config,
        data,
        logs,
    })
}

/// Parse and resolve the template before it is written, so a broken template is a bug that
/// fails before the folder is touched rather than a broken setup for the operator.
fn validate_template() -> Result<(), InitError> {
    let path = Path::new(config::DEFAULT_CONFIG_FILE);
    let file = config::parse(TEMPLATE, path).map_err(|error| InitError::Template {
        reason: error.to_string(),
    })?;
    Config::resolve(Some(file), Overrides::default()).map_err(|error| InitError::Template {
        reason: error.to_string(),
    })?;
    Ok(())
}

#[cfg(test)]
mod tests {
    use std::time::Duration;

    use super::*;
    use crate::config::ChannelSettings;
    use crate::probe::Method;

    fn resolved() -> Config {
        let file = config::parse(TEMPLATE, Path::new(config::DEFAULT_CONFIG_FILE))
            .expect("the template parses");
        Config::resolve(Some(file), Overrides::default()).expect("the template resolves")
    }

    #[test]
    fn the_template_resolves() {
        let config = resolved();
        assert_eq!(config.targets.len(), 1);
        let target = &config.targets[0];
        assert_eq!(target.method(), Method::Tcp);
        assert!(target.interface.is_none());
        assert_eq!(config.database, PathBuf::from(DATABASE));
        assert_eq!(config.notify.channels.len(), 1);
        match &config.notify.channels[0] {
            ChannelSettings::LogFile(settings) => {
                assert_eq!(settings.name, "events");
                assert!(
                    settings.filename.ends_with(EVENT_LOG),
                    "filename: {}",
                    settings.filename.display()
                );
                assert!(TEMPLATE.contains("filename = \"logs/events.log\""));
                assert_eq!(settings.stabilize, Duration::ZERO);
                assert_eq!(settings.max_bytes, 10_485_760);
                assert_eq!(settings.max_files, 5);
            }
            other => panic!("unexpected channel: {other:?}"),
        }
        assert!(config.notify.global.iter().any(|name| name == "events"));
    }

    #[test]
    fn the_template_keeps_icmp_out_of_the_active_targets() {
        let config = resolved();
        assert!(config
            .targets
            .iter()
            .all(|target| target.method() != Method::Icmp));
        assert!(TEMPLATE.contains("# method = \"icmp\""));
    }

    #[test]
    fn a_missing_folder_is_created() {
        let root = tempfile::tempdir().expect("a temporary directory");
        let folder = root.path().join("nested/monitor");

        let report = run(&folder).expect("init succeeds");

        assert_eq!(report.config, folder.join(config::DEFAULT_CONFIG_FILE));
        assert!(report.config.is_file());
        assert!(report.data.is_dir());
        assert!(report.logs.is_dir());
    }

    #[test]
    fn an_empty_folder_is_filled() {
        let folder = tempfile::tempdir().expect("a temporary directory");

        let report = run(folder.path()).expect("init succeeds");

        assert!(report.config.is_file());
        assert!(report.data.is_dir());
        assert!(report.logs.is_dir());
    }

    #[test]
    fn a_non_empty_folder_is_refused() {
        let folder = tempfile::tempdir().expect("a temporary directory");
        let kept = folder.path().join("keep.txt");
        fs::write(&kept, "keep").expect("the file is written");

        let error = run(folder.path()).expect_err("the folder is not empty");

        assert!(matches!(error, InitError::NotEmpty { .. }));
        assert!(!folder.path().join(config::DEFAULT_CONFIG_FILE).exists());
        assert_eq!(fs::read_to_string(&kept).expect("the file is read"), "keep");
    }

    #[test]
    fn a_file_is_not_a_directory() {
        let root = tempfile::tempdir().expect("a temporary directory");
        let file = root.path().join("not-a-folder");
        fs::write(&file, "x").expect("the file is written");

        let error = run(&file).expect_err("a file is not a folder");

        assert!(matches!(error, InitError::NotADirectory { .. }));
    }

    #[test]
    fn a_second_run_is_refused() {
        let folder = tempfile::tempdir().expect("a temporary directory");
        let report = run(folder.path()).expect("the first run succeeds");
        let first = fs::read(&report.config).expect("the configuration is read");

        let error = run(folder.path()).expect_err("the second run is refused");

        assert!(matches!(error, InitError::NotEmpty { .. }));
        assert_eq!(
            fs::read(&report.config).expect("the configuration is read"),
            first
        );
    }

    #[test]
    fn the_report_lists_the_paths_and_commands() {
        let folder = tempfile::tempdir().expect("a temporary directory");
        let report = run(folder.path()).expect("init succeeds");

        let text = report.render();

        assert!(text.contains(&report.config.display().to_string()));
        assert!(text.contains(&report.data.display().to_string()));
        assert!(text.contains(&report.logs.display().to_string()));
        assert!(text.contains("uptime-monitor check --config"));
        assert!(text.contains("uptime-monitor monitor --config"));
    }
}
